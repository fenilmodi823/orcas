"""Generate the 19 major moons' IAU rotation tables (S6b) from NAIF's pck00011.tpc.

Prints the TypeScript rows for `packages/orcas-physics/src/iau-moon-poles.ts`: each moon's prime
meridian W = W0 + W1 d + W2 d^2 (d in days TDB from J2000) plus every non-zero periodic term
a sin(theta), theta = theta0 + theta1 T (T in Julian centuries), from BODYnnn_PM,
BODYnnn_NUT_PREC_PM and the BODYn_NUT_PREC_ANGLES they multiply. It also regenerates the poles
and checks them against the committed table, so the parser is tested against the 2026-10-12
transcription.

Mars's angles are quadratic (BODY4_MAX_PHASE_DEGREE = 2: a list of triples). Only one term the
moons use has a non-zero quadratic coefficient, Phobos's forced libration in W (-1.143 deg),
written as a fourth number, theta2 in degrees per century squared.
Run from the repo root:  python scripts/data/gen_moon_rotation.py
"""

from __future__ import annotations

import re
from pathlib import Path

PCK = Path("data/ephemeris/pck00011.tpc")
MOON_TABLE = Path("packages/orcas-physics/src/iau-moon-poles.ts")
MOONS = {
    401: "Phobos",
    402: "Deimos",
    501: "Io",
    502: "Europa",
    503: "Ganymede",
    504: "Callisto",
    601: "Mimas",
    602: "Enceladus",
    603: "Tethys",
    604: "Dione",
    605: "Rhea",
    606: "Titan",
    608: "Iapetus",
    701: "Ariel",
    702: "Umbriel",
    703: "Titania",
    704: "Oberon",
    705: "Miranda",
    801: "Triton",
}


def read_kernel(path: Path) -> dict[str, list[float]]:
    """Every assignment inside the kernel's \\begindata blocks; a later one replaces an earlier."""
    text = path.read_text(encoding="utf8", errors="replace")
    data: dict[str, list[float]] = {}
    for block in re.findall(r"\\begindata(.*?)(?=\\begintext|\Z)", text, flags=re.S):
        for name, body in re.findall(r"(BODY\w+)\s*=\s*\(([^)]*)\)", block):
            data[name] = [float(v.replace("D", "E")) for v in body.replace(",", " ").split()]
        for name, value in re.findall(r"(BODY\w+)\s*=\s*([-+0-9.EeD]+)\s*$", block, flags=re.M):
            data.setdefault(name, [float(value.replace("D", "E"))])
    return data


def angles(data: dict[str, list[float]], system: int) -> list[tuple[float, float, float]]:
    """A system's nutation-precession angles (theta0, theta1, theta2): deg, deg/cy, deg/cy^2."""
    raw = data.get(f"BODY{system}_NUT_PREC_ANGLES", [])
    degree = int(data.get(f"BODY{system}_MAX_PHASE_DEGREE", [1])[0])
    width = degree + 1
    padding = [0.0] * (3 - width)
    return [tuple(raw[i : i + width] + padding) for i in range(0, len(raw), width)]  # type: ignore[misc]


def terms(
    coeffs: list[float], angle_list: list[tuple[float, float, float]]
) -> list[tuple[float, ...]]:
    """Each non-zero term as (amplitude, theta0, theta1), plus theta2 if its angle is quadratic."""
    return [
        (amp, t0, t1, t2) if t2 else (amp, t0, t1)
        for amp, (t0, t1, t2) in zip(coeffs, angle_list, strict=False)
        if amp != 0
    ]


def ts_terms(ts: list[tuple[float, ...]]) -> str:
    return "[" + ", ".join("[" + ", ".join(repr(v) for v in t) + "]" for t in ts) + "]"


def main() -> None:
    data = read_kernel(PCK)
    committed = MOON_TABLE.read_text(encoding="utf8")
    print("// IAU_MOON_PRIME_MERIDIANS rows, generated by scripts/data/gen_moon_rotation.py")
    for naif, name in MOONS.items():
        system = naif // 100
        angle_list = angles(data, system)
        w = data[f"BODY{naif}_PM"] + [0.0, 0.0]
        w_terms = terms(data.get(f"BODY{naif}_NUT_PREC_PM", []), angle_list)
        ra = data[f"BODY{naif}_POLE_RA"]
        dec = data[f"BODY{naif}_POLE_DEC"]
        ra_terms = terms(data.get(f"BODY{naif}_NUT_PREC_RA", []), angle_list)
        dec_terms = terms(data.get(f"BODY{naif}_NUT_PREC_DEC", []), angle_list)
        # Every number of the committed pole row must be what this parser reads from the kernel.
        row = re.search(rf"^\s*{naif}: moonPole\((.*)\), // {name}$", committed, flags=re.M)
        want = [ra[0], ra[1], dec[0], dec[1]] + [v for t in ra_terms + dec_terms for v in t]
        got = (
            [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?(?:e-?\d+)?", row.group(1))]
            if row
            else []
        )
        if got != want:
            raise SystemExit(f"{name}: committed pole row {got} != pck {want}")
        quad = f", {w[2]!r}" if w[2] != 0 else ""
        tail = f", {ts_terms(w_terms)}" if w_terms else (", []" if quad else "")
        print(f"  {naif}: moonPm({w[0]!r}, {w[1]!r}{tail}{quad}), // {name}")


if __name__ == "__main__":
    main()
